#!/usr/bin/env python3
"""Generate shared controller/TV translations from the reviewed TSV source."""
from pathlib import Path
import csv,json,re
root=Path(__file__).resolve().parents[1]
rows=list(csv.reader((root/'locales/player-ui.tsv').open(),delimiter='\t'))
langs=rows.pop(0);catalog={lang:{} for lang in langs}
for n,row in enumerate(rows,2):
 if len(row)!=len(langs):raise SystemExit(f'Line {n}: expected {len(langs)} translations, got {len(row)}')
 key=row[0]
 if key in catalog['en']:raise SystemExit(f'Duplicate: {key}')
 for lang,value in zip(langs,row):
  if not value or sorted(re.findall(r'\{\d+\}',value))!=sorted(re.findall(r'\{\d+\}',key)):raise SystemExit(f'Invalid {lang}: {key}')
  catalog[lang][key]=value
out=json.dumps(catalog,ensure_ascii=False,indent=2)+'\n'
(root/'android-host/app/src/main/assets/player-ui.json').write_text(out)
(root/'spike/locales.mjs').write_text('// Generated by scripts/build-locales.py\nexport const catalog='+out.rstrip()+';\n')
print(f'{len(langs)} languages, {len(catalog["en"])} shared messages; placeholders checked.')
